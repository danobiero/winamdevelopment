-- ============================================================
-- SQL MIGRATION: ANNUAL DIVIDEND DECLARATIONS TABLE
-- ============================================================
-- Run this in your Supabase SQL Editor to create the native
-- relational table for tracking annual dividend declarations
-- per investment opportunity.

CREATE TABLE IF NOT EXISTS public.dividend_declarations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_id BIGINT NOT NULL REFERENCES public.opportunities(id) ON DELETE CASCADE,
  fiscal_year INTEGER NOT NULL,
  declared_amount NUMERIC(12, 2) NOT NULL CHECK (declared_amount > 0),
  opportunity_nav_at_declaration NUMERIC(12, 2) NOT NULL DEFAULT 0,
  total_invested_at_declaration NUMERIC(12, 2) NOT NULL DEFAULT 0,
  net_surplus_at_declaration NUMERIC(12, 2) NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'pending_approval' CHECK (
    status IN ('pending_approval', 'approved', 'partially_paid', 'completed')
  ),
  declaration_date DATE NOT NULL DEFAULT CURRENT_DATE,
  approved_at TIMESTAMPTZ,
  approved_by TEXT,
  created_by TEXT,
  notes TEXT,
  allocations_snapshot JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT unique_dividend_per_opportunity_year UNIQUE (opportunity_id, fiscal_year)
);

CREATE INDEX IF NOT EXISTS idx_dividend_declarations_opp_year
  ON public.dividend_declarations(opportunity_id, fiscal_year);
